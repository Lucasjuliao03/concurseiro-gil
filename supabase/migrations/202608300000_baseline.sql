-- Reproducible baseline for a fresh SAFO Supabase project.
begin;

create extension if not exists pgcrypto;

create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.edicts (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  name text not null,
  year integer not null check (year between 1900 and 2200),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.edict_subjects (
  edict_id bigint not null references public.edicts(id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  exam_weight numeric(8,2),
  question_count integer,
  sort_order integer not null default 0,
  primary key (edict_id, subject_id)
);

create table if not exists public.topics (
  id bigint generated by default as identity primary key,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  name text not null,
  description text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (subject_id, name)
);

create table if not exists public.subtopics (
  id bigint generated by default as identity primary key,
  topic_id bigint not null references public.topics(id) on delete cascade,
  name text not null,
  sort_order integer not null default 0,
  unique (topic_id, name)
);

create table if not exists public.exam_boards (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  edict_id bigint references public.edicts(id) on delete set null,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  topic_id bigint references public.topics(id) on delete cascade,
  subtopic_id bigint references public.subtopics(id) on delete set null,
  board_id bigint references public.exam_boards(id) on delete set null,
  question_type text not null default 'banca' check (question_type in ('banca','ia')),
  difficulty text not null default 'medium' check (difficulty in ('easy','medium','hard')),
  source_year integer,
  statement text not null,
  option_a text not null,
  option_b text not null,
  option_c text,
  option_d text,
  option_e text,
  correct_option text not null check (upper(correct_option) in ('A','B','C','D','E')),
  explanation text,
  status text not null default 'draft' check (status in ('draft','published','archived')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.flashcards (
  id bigint generated by default as identity primary key,
  edict_id bigint references public.edicts(id) on delete set null,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  topic_id bigint references public.topics(id) on delete cascade,
  front_text text not null,
  back_text text not null,
  difficulty text not null default 'medium' check (difficulty in ('easy','medium','hard')),
  status text not null default 'draft' check (status in ('draft','published','archived')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.summaries (
  id bigint generated by default as identity primary key,
  edict_id bigint references public.edicts(id) on delete set null,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  topic_id bigint references public.topics(id) on delete cascade,
  subtopic_id bigint references public.subtopics(id) on delete set null,
  title text not null,
  format text not null default 'markdown' check (format in ('markdown','html','pdf')),
  content_html text,
  content_markdown text,
  sort_order integer not null default 0,
  status text not null default 'draft' check (status in ('draft','published','archived')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text,
  full_name text not null default '',
  role text not null default 'student' check (role in ('student','admin')),
  is_active boolean not null default false,
  course_id bigint references public.courses(id) on delete set null,
  active_until timestamptz,
  xp_total integer not null default 0 check (xp_total >= 0),
  streak_days integer not null default 0 check (streak_days >= 0),
  last_access_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.question_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  question_id bigint not null references public.questions(id) on delete cascade,
  selected_option text not null,
  is_correct boolean not null,
  created_at timestamptz not null default now()
);

-- Legacy SAFO installations used answered_at/reviewed_at instead of created_at.
-- Normalize those installations before the hardening migration creates indexes
-- and server-side progress functions. These statements are safe on fresh databases.
alter table public.question_attempts
  add column if not exists created_at timestamptz;
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'question_attempts' and column_name = 'answered_at'
  ) then
    execute 'update public.question_attempts set created_at = coalesce(created_at, answered_at)';
  end if;
end $$;
update public.question_attempts set created_at = now() where created_at is null;
alter table public.question_attempts alter column created_at set default now();
alter table public.question_attempts alter column created_at set not null;

create table if not exists public.user_question_stats (
  user_id uuid not null references public.profiles(id) on delete cascade,
  question_id bigint not null references public.questions(id) on delete cascade,
  total_attempts integer not null default 0,
  total_correct integer not null default 0,
  total_wrong integer not null default 0,
  first_answered_at timestamptz,
  last_answered_at timestamptz,
  last_selected_option text,
  last_is_correct boolean,
  primary key (user_id, question_id)
);

create table if not exists public.user_flashcard_reviews (
  user_id uuid not null references public.profiles(id) on delete cascade,
  flashcard_id bigint not null references public.flashcards(id) on delete cascade,
  total_reviews integer not null default 0,
  total_correct integer not null default 0,
  total_wrong integer not null default 0,
  current_interval_days integer not null default 1,
  last_review_result text,
  last_reviewed_at timestamptz,
  next_review_at timestamptz,
  memory_stage integer not null default 1,
  is_mastered boolean not null default false,
  primary key (user_id, flashcard_id)
);

create table if not exists public.flashcard_review_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  flashcard_id bigint not null references public.flashcards(id) on delete cascade,
  review_result text not null check (review_result in ('wrong','hard','good','easy')),
  interval_after integer not null,
  created_at timestamptz not null default now()
);

alter table public.flashcard_review_logs
  add column if not exists created_at timestamptz;
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'flashcard_review_logs' and column_name = 'reviewed_at'
  ) then
    execute 'update public.flashcard_review_logs set created_at = coalesce(created_at, reviewed_at)';
  end if;
end $$;
update public.flashcard_review_logs set created_at = now() where created_at is null;
alter table public.flashcard_review_logs alter column created_at set default now();
alter table public.flashcard_review_logs alter column created_at set not null;

create table if not exists public.user_xp_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  source_type text not null,
  source_id bigint,
  xp_amount integer not null check (xp_amount >= 0),
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.user_daily_productivity (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  productivity_date date not null,
  questions_answered integer not null default 0,
  questions_correct integer not null default 0,
  questions_wrong integer not null default 0,
  flashcards_reviewed integer not null default 0,
  xp_earned integer not null default 0,
  unique (user_id, productivity_date)
);

create table if not exists public.user_achievements (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  achievement_id text not null,
  unlocked_at timestamptz not null default now(),
  notification_shown boolean not null default false,
  created_at timestamptz not null default now(),
  unique (user_id, achievement_id)
);

create table if not exists public.levels (
  id bigint generated by default as identity primary key,
  level_number integer not null unique,
  title text not null,
  min_xp integer not null
);

create table if not exists public.achievements (
  id bigint generated by default as identity primary key,
  code text not null unique,
  title text not null,
  description text,
  achievement_type text,
  xp_reward integer not null default 0,
  is_active boolean not null default true
);

create table if not exists public.motivational_messages (
  id bigint generated by default as identity primary key,
  title text,
  message text not null,
  author text,
  theme text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists idx_questions_subject_topic on public.questions(subject_id, topic_id);
create index if not exists idx_flashcards_subject_topic on public.flashcards(subject_id, topic_id);
create index if not exists idx_summaries_subject_topic on public.summaries(subject_id, topic_id);
create index if not exists idx_productivity_user_date on public.user_daily_productivity(user_id, productivity_date desc);

commit;
