create or replace function public.record_question_answer(
  p_question_id bigint,
  p_selected_option text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_q public.questions%rowtype;
  v_selected text := upper(trim(p_selected_option));
  v_correct boolean;
  v_had_wrong boolean;
  v_xp integer;
  v_streak integer;
  v_unlocked text[];
  v_today date := (now() at time zone 'America/Sao_Paulo')::date;
  v_hour integer := extract(hour from now() at time zone 'America/Sao_Paulo');
begin
  perform public.assert_study_access('content');
  if v_selected not in ('A','B','C','D','E') then
    raise exception using errcode = '22023', message = 'INVALID_OPTION';
  end if;

  select * into v_q from public.questions
  where id = p_question_id and is_active = true and status = 'published';
  if not found or not public.can_access_study_content(v_q.edict_id, v_q.subject_id) then
    raise exception using errcode = '42501', message = 'QUESTION_NOT_AVAILABLE';
  end if;

  select exists (
    select 1 from public.question_attempts
    where user_id = auth.uid() and question_id = p_question_id and is_correct = false
  ) into v_had_wrong;
  v_correct := v_selected = upper(v_q.correct_option);
  v_xp := case when v_correct then 15 else 3 end;

  insert into public.question_attempts
    (user_id, question_id, selected_option, is_correct)
  values (auth.uid(), p_question_id, v_selected, v_correct);

  insert into public.user_question_stats
    (user_id, question_id, total_attempts, total_correct, total_wrong,
     first_answered_at, last_answered_at, last_selected_option, last_is_correct)
  values
    (auth.uid(), p_question_id, 1, case when v_correct then 1 else 0 end,
     case when v_correct then 0 else 1 end, now(), now(), v_selected, v_correct)
  on conflict (user_id, question_id) do update set
    total_attempts = public.user_question_stats.total_attempts + 1,
    total_correct = public.user_question_stats.total_correct + case when v_correct then 1 else 0 end,
    total_wrong = public.user_question_stats.total_wrong + case when v_correct then 0 else 1 end,
    last_answered_at = now(), last_selected_option = v_selected, last_is_correct = v_correct;

  insert into public.user_xp_logs
    (user_id, source_type, source_id, xp_amount, description)
  values (auth.uid(), 'question', p_question_id, v_xp,
    case when v_correct then 'Acerto em questão' else 'Tentativa de questão' end);
  update public.profiles set xp_total = coalesce(xp_total,0) + v_xp where id = auth.uid();

  insert into public.user_daily_productivity
    (user_id, productivity_date, questions_answered, questions_correct, questions_wrong, xp_earned)
  values (auth.uid(), v_today, 1, case when v_correct then 1 else 0 end,
    case when v_correct then 0 else 1 end, v_xp)
  on conflict (user_id, productivity_date) do update set
    questions_answered = public.user_daily_productivity.questions_answered + 1,
    questions_correct = public.user_daily_productivity.questions_correct + case when v_correct then 1 else 0 end,
    questions_wrong = public.user_daily_productivity.questions_wrong + case when v_correct then 0 else 1 end,
    xp_earned = public.user_daily_productivity.xp_earned + v_xp;

  v_streak := public.update_my_streak(auth.uid());
  if v_correct and v_had_wrong then perform public.award_achievement(auth.uid(), 'comeback'); end if;
  if v_hour < 6 then perform public.award_achievement(auth.uid(), 'early_bird'); end if;
  if v_hour = 0 then perform public.award_achievement(auth.uid(), 'night_owl'); end if;
  if v_correct and not exists (
    select 1 from (select is_correct from public.question_attempts
      where user_id = auth.uid() order by created_at desc limit 5) x where not is_correct
  ) and (select count(*) from (select 1 from public.question_attempts
      where user_id = auth.uid() order by created_at desc limit 5) y) = 5 then
    perform public.award_achievement(auth.uid(), 'perfect_session');
  end if;
  if (select count(*) from (select created_at from public.question_attempts
      where user_id = auth.uid() order by created_at desc limit 10) z
      where created_at >= now() - interval '5 minutes') = 10 then
    perform public.award_achievement(auth.uid(), 'speed_demon');
  end if;
  if v_correct and v_q.topic_id is not null
    and not exists (select 1 from public.question_attempts qa
      join public.questions q2 on q2.id = qa.question_id
      where qa.user_id = auth.uid() and q2.topic_id = v_q.topic_id and qa.is_correct = false)
    and (select count(distinct qa.question_id) from public.question_attempts qa
      join public.questions q2 on q2.id = qa.question_id
      where qa.user_id = auth.uid() and q2.topic_id = v_q.topic_id)
      >= (select count(*) from public.questions q3
          where q3.topic_id = v_q.topic_id and q3.is_active and q3.status = 'published') then
    perform public.award_achievement(auth.uid(), 'no_mistakes_topic');
  end if;

  v_unlocked := public.sync_my_achievements(auth.uid());
  return jsonb_build_object(
    'is_correct', v_correct,
    'correct_option', lower(v_q.correct_option),
    'explanation', coalesce(v_q.explanation,''),
    'xp_awarded', v_xp,
    'streak', v_streak,
    'unlocked', v_unlocked
  );
end;
$$;

create or replace function public.record_flashcard_review(
  p_flashcard_id bigint,
  p_result text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_card public.flashcards%rowtype;
  v_interval integer;
  v_correct boolean;
  v_today date := (now() at time zone 'America/Sao_Paulo')::date;
  v_unlocked text[];
begin
  perform public.assert_study_access('content');
  v_interval := case p_result when 'wrong' then 1 when 'hard' then 2 when 'good' then 4 when 'easy' then 7 else null end;
  if v_interval is null then raise exception using errcode = '22023', message = 'INVALID_REVIEW_RESULT'; end if;

  select * into v_card from public.flashcards
  where id = p_flashcard_id and is_active = true and status = 'published';
  if not found or not public.can_access_study_content(v_card.edict_id, v_card.subject_id) then
    raise exception using errcode = '42501', message = 'FLASHCARD_NOT_AVAILABLE';
  end if;
  v_correct := p_result <> 'wrong';

  insert into public.user_flashcard_reviews
    (user_id, flashcard_id, total_reviews, total_correct, total_wrong,
     current_interval_days, last_review_result, last_reviewed_at, next_review_at, memory_stage, is_mastered)
  values (auth.uid(), p_flashcard_id, 1, case when v_correct then 1 else 0 end,
    case when v_correct then 0 else 1 end, v_interval, p_result, now(),
    now() + make_interval(days => v_interval), case when v_correct then 2 else 1 end, false)
  on conflict (user_id, flashcard_id) do update set
    total_reviews = public.user_flashcard_reviews.total_reviews + 1,
    total_correct = public.user_flashcard_reviews.total_correct + case when v_correct then 1 else 0 end,
    total_wrong = public.user_flashcard_reviews.total_wrong + case when v_correct then 0 else 1 end,
    current_interval_days = v_interval, last_review_result = p_result,
    last_reviewed_at = now(), next_review_at = now() + make_interval(days => v_interval),
    memory_stage = case when v_correct then least(public.user_flashcard_reviews.memory_stage + 1, 10) else 1 end,
    is_mastered = v_correct and public.user_flashcard_reviews.memory_stage >= 5;

  insert into public.flashcard_review_logs
    (user_id, flashcard_id, review_result, interval_after)
  values (auth.uid(), p_flashcard_id, p_result, v_interval);
  update public.profiles set xp_total = coalesce(xp_total,0) + 5 where id = auth.uid();
  insert into public.user_daily_productivity
    (user_id, productivity_date, flashcards_reviewed, xp_earned)
  values (auth.uid(), v_today, 1, 5)
  on conflict (user_id, productivity_date) do update set
    flashcards_reviewed = public.user_daily_productivity.flashcards_reviewed + 1,
    xp_earned = public.user_daily_productivity.xp_earned + 5;
  perform public.update_my_streak(auth.uid());
  v_unlocked := public.sync_my_achievements(auth.uid());
  return jsonb_build_object('xp_awarded',5,'unlocked',v_unlocked);
end;
$$;

