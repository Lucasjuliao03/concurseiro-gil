create or replace function public.assert_study_access(p_kind text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile public.profiles%rowtype;
  v_usage bigint;
begin
  if auth.uid() is null then
    raise exception using errcode = '42501', message = 'AUTH_REQUIRED';
  end if;

  select * into v_profile from public.profiles where id = auth.uid();
  if not found then
    raise exception using errcode = '42501', message = 'PROFILE_NOT_FOUND';
  end if;
  if v_profile.active_until is not null and v_profile.active_until < now() then
    raise exception using errcode = '42501', message = 'ACCESS_EXPIRED';
  end if;
  if v_profile.role = 'admin' or v_profile.is_active then
    return;
  end if;

  if p_kind = 'summary' then
    select count(*) into v_usage from public.summary_views where user_id = auth.uid();
    if v_usage >= 2 then
      raise exception using errcode = '42501', message = 'FREE_SUMMARY_LIMIT_REACHED';
    end if;
  else
    select
      (select count(*) from public.question_attempts where user_id = auth.uid()) +
      (select count(*) from public.flashcard_review_logs where user_id = auth.uid())
    into v_usage;
    if v_usage >= 10 then
      raise exception using errcode = '42501', message = 'FREE_CONTENT_LIMIT_REACHED';
    end if;
  end if;
end;
$$;

create or replace function public.update_my_streak(p_user_id uuid)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_last date;
  v_streak integer;
  v_today date := (now() at time zone 'America/Sao_Paulo')::date;
begin
  select (last_access_at at time zone 'America/Sao_Paulo')::date, coalesce(streak_days, 0)
    into v_last, v_streak
  from public.profiles where id = p_user_id for update;

  if v_last = v_today then
    null;
  elsif v_last = v_today - 1 then
    v_streak := v_streak + 1;
  else
    v_streak := 1;
  end if;

  update public.profiles
  set streak_days = v_streak, last_access_at = now()
  where id = p_user_id;
  return v_streak;
end;
$$;

create or replace function public.award_achievement(p_user_id uuid, p_achievement_id text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reward integer;
  v_inserted text;
begin
  select xp_reward into v_reward
  from public.achievement_catalog where id = p_achievement_id;
  if not found then return false; end if;

  insert into public.user_achievements
    (user_id, achievement_id, unlocked_at, notification_shown)
  values (p_user_id, p_achievement_id, now(), false)
  on conflict (user_id, achievement_id) do nothing
  returning achievement_id into v_inserted;

  if v_inserted is not null and v_reward > 0 then
    update public.profiles
    set xp_total = coalesce(xp_total, 0) + v_reward
    where id = p_user_id;
  end if;
  return v_inserted is not null;
end;
$$;

create or replace function public.sync_my_achievements(p_user_id uuid)
returns text[]
language plpgsql
security definer
set search_path = public
as $$
declare
  v_questions bigint;
  v_correct bigint;
  v_flashcards bigint;
  v_summaries bigint;
  v_xp bigint;
  v_streak integer;
  v_item record;
  v_metric bigint;
  v_unlocked text[] := '{}';
begin
  if p_user_id <> auth.uid() then
    raise exception using errcode = '42501', message = 'FORBIDDEN';
  end if;

  select coalesce(sum(total_attempts),0), coalesce(sum(total_correct),0)
    into v_questions, v_correct
  from public.user_question_stats where user_id = p_user_id;
  select coalesce(sum(total_reviews),0) into v_flashcards
  from public.user_flashcard_reviews where user_id = p_user_id;
  select count(*) into v_summaries from public.summary_views where user_id = p_user_id;
  select coalesce(xp_total,0), coalesce(streak_days,0) into v_xp, v_streak
  from public.profiles where id = p_user_id;

  for v_item in select * from public.achievement_catalog where category <> 'special' loop
    v_metric := case v_item.category
      when 'questions' then v_questions
      when 'accuracy' then v_correct
      when 'flashcards' then v_flashcards
      when 'summaries' then v_summaries
      when 'streak' then v_streak
      when 'xp' then v_xp
      when 'rank' then v_xp
      else 0 end;
    if v_metric >= v_item.requirement and public.award_achievement(p_user_id, v_item.id) then
      v_unlocked := array_append(v_unlocked, v_item.id);
      select coalesce(xp_total,0) into v_xp from public.profiles where id = p_user_id;
    end if;
  end loop;
  return v_unlocked;
end;
$$;

